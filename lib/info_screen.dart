/// Endpoint of the Cloudflare Worker proxy (same backend as chat & quiz).
/// The OpenRouter API key stays server-side inside the worker, and the worker
/// owns the model chain (primary + fallbacks), so the app never carries either.
const String kProxyUrl = 'https://mindspark-ai-proxy.adamed135.workers.dev';

/// AI generation settings for the daily info fact.
const int kInfoMaxTokens = 1024;

/// Subjects a daily fact can come from — the same classes allowed in chat.
enum InfoSubject { science, physics, math, geography, history }

extension InfoSubjectInfo on InfoSubject {
  String get translationKey => switch (this) {
        InfoSubject.science => 'science',
        InfoSubject.physics => 'physics',
        InfoSubject.math => 'math',
        InfoSubject.geography => 'geography',
        InfoSubject.history => 'history',
      };

  IconData get icon => switch (this) {
        InfoSubject.science => Icons.science_rounded,
        InfoSubject.physics => Icons.bolt_rounded,
        InfoSubject.math => Icons.calculate_rounded,
        InfoSubject.geography => Icons.public_rounded,
        InfoSubject.history => Icons.history_edu_rounded,
      };

  List<Color> get colors => switch (this) {
        InfoSubject.science => const [Color(0xFF26A69A), Color(0xFF66BB6A)],
        InfoSubject.physics => const [Color(0xFF42A5F5), Color(0xFF7E57C2)],
        InfoSubject.math => const [Color(0xFF5C6BC0), Color(0xFF29B6F6)],
        InfoSubject.geography => const [Color(0xFFEF6C00), Color(0xFFD4E157)],
        InfoSubject.history => const [Color(0xFF7E57C2), Color(0xFFAB47BC)],
      };
}

/// One generated daily fact: a catchy title plus a short kid-friendly text.
class InfoFact {
  const InfoFact({this.title, required this.fact, required this.subject});

  final String? title;
  final String fact;
  final InfoSubject subject;

  Map<String, dynamic> toMap() => {
        'title': title,
        'fact': fact,
        'subject': subject.name,
      };

  static InfoFact fromMap(Map<String, dynamic> map) => InfoFact(
        title: (map['title'] as String?)?.trim().isEmpty == true
            ? null
            : (map['title'] as String?)?.trim(),
        fact: (map['fact'] as String?)?.trim() ?? '',
        subject: InfoSubject.values.firstWhere(
          (s) => s.name == map['subject'],
          orElse: () => InfoSubject.science,
        ),
      );
}

enum _InfoPhase { loading, ready, error }

/// "Info of the Day" screen: one fresh, kid-friendly fact per day,
/// generated by the AI. Facts are cached locally so the whole day shows
/// the same fact (the child can tap "New fact" to get another one).
class InfoOfTheDayScreen extends StatefulWidget {
  const InfoOfTheDayScreen({super.key, required this.appState});

  final AppState appState;

  @override
  State<InfoOfTheDayScreen> createState() => _InfoOfTheDayScreenState();
}

class _InfoOfTheDayScreenState extends State<InfoOfTheDayScreen> {
  static const _dateKey = 'info_fact_date';
  static const _factKey = 'info_fact_json';

  _InfoPhase _phase = _InfoPhase.loading;
  InfoFact? _fact;
  InfoSubject? _selectedSubject; // null = surprise me

  AppState get appState => widget.appState;

  @override
  void initState() {
    super.initState();
    _loadTodayFact();
  }

  /// Local date key (yyyy-mm-dd) used to decide if today's fact is cached.
  String _todayKey() {
    final now = DateTime.now();
    final mm = now.month.toString().padLeft(2, '0');
    final dd = now.day.toString().padLeft(2, '0');
    return '${now.year}-$mm-$dd';
  }

  Future<void> _loadTodayFact({bool forceNew = false}) async {
    setState(() {
      _phase = _InfoPhase.loading;
      _fact = null;
    });

    try {
      final prefs = await SharedPreferences.getInstance();
      final today = _todayKey();

      if (!forceNew) {
        final savedDate = prefs.getString(_dateKey);
        final savedJson = prefs.getString(_factKey);
        if (savedDate == today && savedJson != null) {
          final fact = _tryDecodeFact(savedJson);
          if (fact != null) {
            if (!mounted) return;
            setState(() {
              _fact = fact;
              _selectedSubject = fact.subject;
              _phase = _InfoPhase.ready;
            });
            return;
          }
        }
      }

      // Pick the subject: the child's choice, or a random surprise.
      final subject = _selectedSubject ??
          InfoSubject.values[Random().nextInt(InfoSubject.values.length)];
      final fact = await fetchDailyInfo(
        subject: subject,
        languageCode: appState.languageCode,
      );

      await prefs.setString(_dateKey, today);
      await prefs.setString(_factKey, jsonEncode(fact.toMap()));

      if (!mounted) return;
      setState(() {
        _fact = fact;
        _phase = _InfoPhase.ready;
      });
    } catch (_) {
      if (!mounted) return;
      setState(() => _phase = _InfoPhase.error);
    }
  }

  InfoFact? _tryDecodeFact(String raw) {
    try {
      final data = jsonDecode(raw);
      if (data is Map && (data['fact'] ?? '').toString().trim().isNotEmpty) {
        return InfoFact.fromMap(Map<String, dynamic>.from(data));
      }
    } catch (_) {}
    return null;
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: Row(
          children: [
            Icon(Icons.lightbulb_rounded,
                size: 22, color: Theme.of(context).colorScheme.primary),
            const SizedBox(width: 8),
            Text(appState.t('infoOfDay')),
          ],
        ),
      ),
      body: SafeArea(
        child: switch (_phase) {
          _InfoPhase.loading => _buildLoading(),
          _InfoPhase.error => _buildError(),
          _InfoPhase.ready => _buildReady(),
        },
      ),
    );
  }

  Widget _buildLoading() {
    return Center(
      child: Column(
        mainAxisAlignment: MainAxisAlignment.center,
        children: [
          const CircularProgressIndicator(),
          const SizedBox(height: 24),
          Text(appState.t('generatingInfo'),
              style: Theme.of(context).textTheme.titleMedium),
          const SizedBox(height: 8),
          Padding(
            padding: const EdgeInsets.symmetric(horizontal: 40),
            child: Text(
              appState.t('generatingInfoHint'),
              textAlign: TextAlign.center,
              style: Theme.of(context).textTheme.bodyMedium?.copyWith(
                    color: Theme.of(context).colorScheme.onSurfaceVariant,
                  ),
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildError() {
    final colorScheme = Theme.of(context).colorScheme;
    return Center(
      child: Padding(
        padding: const EdgeInsets.all(32),
        child: Column(
          mainAxisAlignment: MainAxisAlignment.center,
          children: [
            Icon(Icons.error_outline_rounded, size: 56, color: colorScheme.error),
            const SizedBox(height: 16),
            Text(
              appState.t('infoLoadError'),
              textAlign: TextAlign.center,
              style: Theme.of(context).textTheme.titleMedium,
            ),
            const SizedBox(height: 24),
            DuoButton(
              label: appState.t('tryAgain'),
              icon: Icons.refresh_rounded,
              onPressed: () => _loadTodayFact(forceNew: true),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildReady() {
    final theme = Theme.of(context);
    final isDark = theme.brightness == Brightness.dark;
    final fact = _fact!;

    return SingleChildScrollView(
      padding: const EdgeInsets.fromLTRB(20, 16, 20, 24),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          // Subject picker chips (Duo-styled, like quiz difficulty chips).
          Text(
            appState.t('chooseSubject'),
            style: theme.textTheme.titleMedium?.copyWith(
              fontWeight: FontWeight.bold,
            ),
          ),
          const SizedBox(height: 12),
          const SizedBox(height: 4),
          _buildSubjectChips(isDark),
          const SizedBox(height: 24),
          // The fact card.
          _buildFactCard(fact, isDark),
          const SizedBox(height: 28),
          DuoButton(
            label: appState.t('newFact'),
            icon: Icons.auto_awesome_rounded,
            onPressed: () => _loadTodayFact(forceNew: true),
          ),
        ],
      ),
    );
  }

  Widget _buildSubjectChips(bool isDark) {
    final chips = <Widget>[
      for (final subject in InfoSubject.values)
        _InfoSubjectChip(
          subject: subject,
          label: appState.t(subject.translationKey),
          selected: _selectedSubject == subject,
          onTap: () {
            setState(() => _selectedSubject = subject);
            _loadTodayFact(forceNew: true);
          },
        ),
    ];
    return Wrap(spacing: 10, runSpacing: 10, children: chips);
  }

  Widget _buildFactCard(InfoFact fact, bool isDark) {
    final subjectColor = fact.subject.colors.first;

    return DecoratedBox(
      decoration: BoxDecoration(
        color: Neu.base(context),
        borderRadius: BorderRadius.circular(24),
        boxShadow: Neu.raised(context, glow: subjectColor),
      ),
      child: Padding(
        padding: const EdgeInsets.all(20),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                Container(
                  width: 44,
                  height: 44,
                  decoration: BoxDecoration(
                    gradient: LinearGradient(
                      colors: fact.subject.colors,
                      begin: Alignment.topLeft,
                      end: Alignment.bottomRight,
                    ),
                    shape: BoxShape.circle,
                  ),
                  child: Icon(fact.subject.icon, color: Colors.white, size: 24),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: Text(
                    appState.t(fact.subject.translationKey),
                    style: TextStyle(
                      color: subjectColor,
                      fontWeight: FontWeight.w800,
                      fontSize: 14,
                    ),
                  ),
                ),
              ],
            ),
            if (fact.title != null) ...[
              const SizedBox(height: 16),
              Text(
                fact.title!,
                style: Theme.of(context).textTheme.titleLarge?.copyWith(
                      fontWeight: FontWeight.w800,
                      height: 1.3,
                    ),
              ),
            ],
            const SizedBox(height: 12),
            Text(
              fact.fact,
              style: TextStyle(
                color: isDark ? const Color(0xFFF1EFEA) : DuoColors.text,
                fontSize: 16,
                height: 1.5,
              ),
            ),
          ],
        ),
      ),
    );
  }
}

/// Small Duo-styled selectable subject chip.
class _InfoSubjectChip extends StatelessWidget {
  const _InfoSubjectChip({
    required this.subject,
    required this.label,
    required this.selected,
    required this.onTap,
  });

  final InfoSubject subject;
  final String label;
  final bool selected;
  final VoidCallback onTap;

  @override
  Widget build(BuildContext context) {
    final isDark = Theme.of(context).brightness == Brightness.dark;

    return GestureDetector(
      onTap: onTap,
      child: Container(
        padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 10),
        decoration: BoxDecoration(
          color: selected
              ? (isDark ? DuoColors.darkSelectedBg : DuoColors.blueLight)
              : Neu.base(context),
          borderRadius: BorderRadius.circular(14),
          boxShadow: selected
              ? Neu.raised(context, glow: DuoColors.blue)
              : Neu.raised(context),
        ),
        child: Row(
          mainAxisSize: MainAxisSize.min,
          children: [
            Icon(
              subject.icon,
              size: 16,
              color: selected
                  ? DuoColors.blueText
                  : (isDark ? const Color(0xFFF1EFEA) : DuoColors.textLight),
            ),
            const SizedBox(width: 6),
            Text(
              label,
              style: TextStyle(
                fontSize: 14,
                fontWeight: FontWeight.w800,
                color: selected
                    ? DuoColors.blueText
                    : (isDark ? const Color(0xFFF1EFEA) : DuoColors.text),
              ),
            ),
          ],
        ),
      ),
    );
  }
}

/// Asks the AI (via the Cloudflare Worker proxy) for one daily fact.
Future<InfoFact> fetchDailyInfo({
  required InfoSubject subject,
  required String languageCode,
}) async {
  final languageName = switch (languageCode) {
    'ar' => 'Arabic',
    'fr' => 'French',
    _ => 'English',
  };

  final prompt = 'Pick ONE amazing, kid-friendly fact for today about '
      '${subject.name}.\n'
      'Rules:\n'
      '- Reply ONLY with valid JSON shaped like: {"title": "...", "fact": "..."}\n'
      '- "title": a short catchy heading of max 8 words.\n'
      '- "fact": 2 to 4 short sentences with simple vocabulary that a child '
      'aged 10 to 15 understands.\n'
      '- The fact must be interesting, positive, factually accurate and '
      'age-appropriate — nothing violent or frightening.\n'
      '- The fact must be globally relevant and country-neutral: do not rely '
      'on any single country’s curriculum or local examples (world capitals, '
      'planets and universal facts are fine).\n'
      '- Write everything in $languageName.\n'
      '- No markdown, no code fences, no text outside the JSON.';

  final response = await http
      .post(
        Uri.parse(kProxyUrl),
        body: jsonEncode({
          'max_tokens': kInfoMaxTokens,
          'temperature': 0.9,
          'messages': [
            {
              'role': 'system',
              'content':
                  'You are an expert educator writing one daily fun fact for '
                      'children aged 10–15 worldwide. You reply ONLY with valid '
                      'JSON — no markdown, no code fences, no text outside it.',
            },
            {'role': 'user', 'content': prompt},
          ],
        }),
        headers: const {'Content-Type': 'application/json'},
      )
      .timeout(const Duration(seconds: 90));

  if (response.statusCode != 200) {
    throw Exception('Server error ${response.statusCode}');
  }

  final data = jsonDecode(utf8.decode(response.bodyBytes)) as Map<String, dynamic>;
  final choices = data['choices'] as List<dynamic>?;
  final content = choices?[0]?['message']?['content'] as String?;
  if (content == null || content.isEmpty) {
    throw Exception('Empty response from AI');
  }

  return parseDailyInfo(content);
}

/// Parses the model reply into an [InfoFact], tolerating code fences and
/// slightly different key names.
InfoFact parseDailyInfo(String raw) {
  var text = raw.trim();

  // Strip markdown code fences if the model added them.
  final fenceMatch = RegExp(r'```(?:json)?\s*([\s\S]*?)```').firstMatch(text);
  if (fenceMatch != null) text = fenceMatch.group(1)!.trim();

  final start = text.indexOf('{');
  final end = text.lastIndexOf('}');
  if (start != -1 && end > start) {
    try {
      final decoded = jsonDecode(text.substring(start, end + 1));
      if (decoded is Map) {
        final factText = (decoded['fact'] ?? decoded['text'] ?? '')
            .toString()
            .trim();
        final title = (decoded['title'] ?? decoded['heading'] ?? '')
            .toString()
            .trim();
        if (factText.isNotEmpty) {
          return InfoFact(
            title: title.isEmpty ? null : title,
            fact: factText,
            subject: InfoSubject.values.firstWhere(
              (s) =>
                  s.name.toLowerCase() ==
                  (decoded['subject'] ?? '').toString().trim().toLowerCase(),
              orElse: () => InfoSubject.science,
            ),
          );
        }
      }
    } catch (_) {}
  }
  throw const FormatException('AI did not return valid info JSON');
}
